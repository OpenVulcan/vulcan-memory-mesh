// syncDebugSeedSequences advances identity sequences after debug-seed upserts so later auto-generated ids stay aligned with the current table maxima.
// syncDebugSeedSequences 用于在调试种子 upsert 完成后推进 identity sequence，确保后续自动 id 与当前表内最大值保持对齐。
func (r *maintenanceRepository) syncDebugSeedSequences(ctx context.Context) error {
	for _, tableName := range []string{"vmm_users", "vmm_teams", "vmm_spaces", "vmm_projects", "vmm_sessions", "vmm_turn_records", "vmm_memory_nodes", "vmm_profile_nodes", "vmm_profile_instructions"} {
		if err := r.syncIdentitySequence(ctx, tableName); err != nil {
			return err
		}
	}
	return nil
}

// syncIdentitySequence aligns one table identity sequence with the current MAX(id) so manual seed rows and later auto ids can coexist safely.
// syncIdentitySequence 用于让某张表的 identity sequence 与当前 MAX(id) 对齐，确保手工种子行和后续自动 id 能安全共存。
func (r *maintenanceRepository) syncIdentitySequence(ctx context.Context, tableName string) error {
	statement := fmt.Sprintf(`
SELECT setval(
	pg_get_serial_sequence($1, 'id'),
	GREATEST(COALESCE((SELECT MAX(id) FROM %s), 1), 1),
	true
)
`, r.maintenanceQualifiedTable(tableName))
	if _, err := r.shared.pool.Exec(ctx, strings.TrimSpace(statement), r.maintenanceQualifiedTable(tableName)); err != nil {
		return fmt.Errorf("sync postgres identity sequence for %s: %w", tableName, err)
	}
	return nil
}

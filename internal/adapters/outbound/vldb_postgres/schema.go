	if r == nil || r.shared == nil || r.shared.pool == nil {
		return fmt.Errorf("postgres store is not initialized")
	}
	callCtx, cancel := r.maintenanceBootstrapContext(ctx)
	defer cancel()

	// Bootstrap the version table before the rest of the schema so incompatible tracked versions fail fast before later DDL mutates more objects.
	// 先初始化版本表，再继续其余 schema，这样版本不兼容时可以在后续 DDL 改动更多对象前快速失败。
	if err := r.ensureSchemaVersionTable(callCtx); err != nil {
		return err
	}
	if err := r.validateTrackedSchemaVersions(callCtx); err != nil {
		return err
	}
	if err := r.applyTrackedSchemaMigrations(callCtx); err != nil {
		return err
	}


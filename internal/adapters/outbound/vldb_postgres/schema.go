// ensureVectorIndex creates the shared pgvector ANN index used by both flavors for first-stage semantic recall.
// ensureVectorIndex 用于创建两种方言共享的 pgvector ANN 索引，服务首阶段语义召回。
func (r *maintenanceRepository) ensureVectorIndex(ctx context.Context) error {
	statement := buildMemoryVectorIndexSQL(r.memoryNodesTable(), r.shared.cfg.VectorLists)
	if _, err := r.shared.pool.Exec(ctx, strings.TrimSpace(statement)); err != nil {
		return fmt.Errorf("create postgres vector index: %w", err)
	}
	return nil
}

// buildMemoryVectorIndexSQL renders the shared ANN index DDL so startup bootstrap and maintenance rebuilds always recreate the same pgvector index definition.
// buildMemoryVectorIndexSQL 用于渲染共享 ANN 索引 DDL，确保启动期初始化与维护期重建始终复用同一份 pgvector 索引定义。
func buildMemoryVectorIndexSQL(memoryTable string, lists int) string {
	return fmt.Sprintf(`
CREATE INDEX IF NOT EXISTS %s ON %s USING ivfflat (embedding vector_cosine_ops) WITH (lists = %d)
`, quoteIdentifier("idx_vmm_memory_nodes_embedding_ivfflat"), memoryTable, lists)
}

// ensureDebugSeedWorkspace inserts the deterministic default user/team/space/project rows expected by local debugging flows.
// ensureDebugSeedWorkspace 用于插入本地调试流期望的确定性默认 user/team/space/project 行。
func (r *maintenanceRepository) ensureDebugSeedWorkspace(ctx context.Context) error {
	if r == nil || r.shared == nil || r.shared.pool == nil {
		return fmt.Errorf("postgres store is not initialized")
	}
	var projectCount int
	countSQL := fmt.Sprintf(`SELECT COUNT(*) FROM %s`, r.projectsTable())
	if err := r.shared.pool.QueryRow(ctx, countSQL).Scan(&projectCount); err != nil {
		return fmt.Errorf("count postgres projects before debug seed bootstrap: %w", err)
	}
	if !shouldSeedDebugWorkspace(projectCount) {
		return nil
	}
	now := time.Now().UTC()
	if _, err := r.upsertDebugSeedUser(ctx, r.shared.pool, logicdomain.DefaultWorkspaceResourceName, now); err != nil {
		return err
	}
	teamID, err := r.upsertDebugSeedTeam(ctx, r.shared.pool, logicdomain.DefaultWorkspaceResourceName, now)
	if err != nil {
		return err
	}
	spaceID, err := r.upsertDebugSeedSpace(ctx, r.shared.pool, teamID, logicdomain.DefaultWorkspaceResourceName, now)
	if err != nil {
		return err
	}
	if _, err := r.upsertDebugSeedProject(ctx, r.shared.pool, teamID, spaceID, logicdomain.DefaultWorkspaceResourceName, now); err != nil {
		return err
	}
	return nil
}

// shouldSeedDebugWorkspace reports whether startup should inject the deterministic default hierarchy, matching SQLite by seeding only truly empty workspaces.
// shouldSeedDebugWorkspace 用于判断启动时是否应注入确定性的默认层级；其语义与 SQLite 保持一致，只在工作区真正为空时补种。
func shouldSeedDebugWorkspace(projectCount int) bool {
	return projectCount == 0
}

// upsertDebugSeedUser resolves or creates the default debug user by name so empty workspaces with restored ids can still bootstrap safely.
// upsertDebugSeedUser 用于按名称解析或创建默认调试用户，确保即使空工作区里的 id 已被恢复过，启动也能安全补种。
func (r *maintenanceRepository) upsertDebugSeedUser(ctx context.Context, q profileQueryer, userName string, now time.Time) (uint64, error) {
	sqlText := fmt.Sprintf(`
INSERT INTO %s (name, profile, delete_confirm_code, created_at, updated_at)
VALUES ($1, '', '', $2, $2)
ON CONFLICT (name)
DO UPDATE SET name = EXCLUDED.name
RETURNING id
`, r.usersTable())
	var userID uint64
	if err := q.QueryRow(ctx, strings.TrimSpace(sqlText), strings.TrimSpace(userName), now.UTC()).Scan(&userID); err != nil {
		return 0, fmt.Errorf("upsert postgres debug seed user: %w", err)
	}
	return userID, nil
}


// postgresSchemaObjectBootstrapError attaches the named table DDL label to startup schema errors so operators can repair the exact failed object.
// postgresSchemaObjectBootstrapError 用于把命名表 DDL 标签附加到启动 schema 错误中，方便运维人员修复具体失败对象。
func postgresSchemaObjectBootstrapError(statement postgresDDLStatement, err error) error {
	return postgresDDLStatementExecutionError("bootstrap postgres schema object", statement, err)
}

// postgresDDLStatement names one schema bootstrap statement so startup failures can identify the exact table or index that failed.
// postgresDDLStatement 用于命名一条 schema 启动语句，让启动失败能够定位到具体失败的表或索引。
type postgresDDLStatement struct {
	// name is the stable diagnostic label for this DDL statement.
	// name 是这条 DDL 语句用于诊断的稳定标签。
	name string
	// sql is the rendered PostgreSQL statement executed during schema bootstrap.
	// sql 是 schema 启动阶段执行的 PostgreSQL 语句。
	sql string
}

// postgresDDLStatementExecutionError attaches a phase and DDL label to one PostgreSQL schema error while preserving the original storage error.
// postgresDDLStatementExecutionError 用于把阶段名和 DDL 标签附加到 PostgreSQL schema 错误上，同时保留原始存储错误。
func postgresDDLStatementExecutionError(phase string, statement postgresDDLStatement, err error) error {
	if err == nil {
		return nil
	}
	return fmt.Errorf("%s %s: %w", strings.TrimSpace(phase), strings.TrimSpace(statement.name), err)
}

// ensureCommonIndexes creates the shared non-lexical indexes reused by both PostgreSQL dialect flavors.
// ensureCommonIndexes 用于创建两种 PostgreSQL 方言都会复用的非 lexical 公共索引。
func (r *maintenanceRepository) ensureCommonIndexes(ctx context.Context) error {
	for _, statement := range postgresCommonIndexStatements(r) {
		if _, err := r.shared.pool.Exec(ctx, strings.TrimSpace(statement.sql)); err != nil {
			return postgresDDLStatementExecutionError("create postgres common index", statement, err)
		}
	}
	return nil
}

